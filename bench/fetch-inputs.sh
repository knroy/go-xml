| peppol/sch, peppol/invoices | OpenPEPPOL peppol-bis-invoice-3, rules/sch, rules/examples | v3.0.20, commit 261c458474e27d58a25be629cccac28883171c92, tar.gz sha256 54b9ada9b866338c629789d30593162f90f1d76654d978266244932aabe02802 | no licence file; CEN rules EUPL-1.2; PEPPOL rules (c) OpenPeppol, no redistribution without consent -- never commit |
| peppol/xsl | compiled by SchXslt 2.0/pipeline-for-svrl.xsl | SchXslt 1.10.1, commit 17f63a42c2d417206e1289cf767359c4fa047919, zip sha256 e141fabd4804a0ea527945dc7253dd38f9ef8957d9b219b94e13d16859cff7f0 | MIT (SchXslt); output inherits the rules' terms |
| xmark | CWI XMark xmlgen unix.c, xmlquery.txt, auction.dtd | unix.c 12f08c20dbcf91e9d7149ffa3d6fb6ba42d5a447940f2294f4c8c7f5d5197bda, xmlquery.txt 53168d556f9b665d7693ed9fde661c8f68f9a60ad4196d829a27a35b10a40791, auction.dtd 994e9a6fb8b9a9a3c1301fe68ff26ab7ddc4c0590619e68abb9d4b8f02076f62 | xmlgen public domain (CWI downloads page); queries/DTD: none stated |
