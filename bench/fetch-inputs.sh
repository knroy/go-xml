	printf '%-34s %10s %6s\n' "testdata/bench/$d" "$(du -sk "$OUT/$d" | cut -f1)" "$(find "$OUT/$d" -type f | wc -l | tr -d ' ')"
done
printf '%-34s %10s %6s\n' "docbook/documents.txt" "-" "$(wc -l < "$OUT/docbook/documents.txt" | tr -d ' ')"
echo "Schematron route:$SCH_ROUTE"
[ -z "$XQ_FAIL" ] || echo "XMark failures:$XQ_FAIL"
