| docbook/documents.txt | paths of DocBook 5 instances in testdata/xsltng (xslTNG, MIT), not copied | testdata/xsltng checkout | MIT |

## XRechnung chain (UBL -> HTML)

1. `xrechnung/xsl/ubl-invoice-xr.xsl` on a UBL Invoice -> intermediate `xr:invoice` XML.
2. `xrechnung/xsl/xrechnung-html.xsl` on that XML -> HTML. Parameters: `lang`
   (default `de`; `en` also shipped), `l10n-nl-lookup` (default `true()`).
   It reads `xrechnung-viewer.css`, `xrechnung-viewer.js` and
   `FileSaver-v2.0.5.js` with `unparsed-text()` (go-xml: `-allow-unparsed-text`)
   and `l10n/<lang>.xml`. CreditNote input would use `ubl-creditnote-xr.xsl`.
   Note: `xrechnung-html.xsl` (version 2.0) puts `xsl:output` before `xsl:import`.

## Peppol validation

Compile: `go-xml -xsl schxslt-1.10.1/2.0/pipeline-for-svrl.xsl -now 2026-03-16T00:00:00Z
-o peppol/xsl/<name>.xsl peppol/sch/<name>.sch`. Validate: apply `peppol/xsl/<name>.xsl`
to each `peppol/invoices/*.xml`; the result is SVRL. Both rule sets apply to every invoice.

## XMark convention

The auction document is the context item: every `doc("auction.xml")` in the
original xmlquery.txt is rewritten to `.`, and the `--` comment lines become
XQuery comments. Run `go-xml xquery -q xmark/queries/qN.xq xmark/auction-F.xml`
(Saxon: `-s:auction-F.xml -q:qN.xq`; BaseX: `-i auction-F.xml qN.xq`).

EOF
echo "Schematron compile route:$SCH_ROUTE"
echo
if [ -n "$XQ_FAIL" ]; then echo "XMark queries failing under go-xml on auction-0.01.xml:$XQ_FAIL"
else echo "XMark queries: q1..q20 all run under go-xml on auction-0.01.xml."; fi
echo
echo "## Generated files (sha256)"
echo
for f in "$X"/auction-*.xml "$OUT"/parse/*.xml "$OUT"/peppol/xsl/*.xsl; do
	echo "- ${f#"$OUT"/} $(sha256 "$f")"
done
echo
echo "DocBook instances listed: $(wc -l < "$OUT/docbook/documents.txt" | tr -d ' ')"
} > "$OUT/SOURCES.md"

# Summary
printf '\n%-34s %10s %6s\n' PATH KB FILES
